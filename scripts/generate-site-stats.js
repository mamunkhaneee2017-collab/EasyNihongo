/* ==========================================
   Regenerates data/site-stats.js — the real
   content counts (lessons/chapters, kanji,
   grammar, vocabulary, quiz questions...) baked
   into a static file so pages show them even
   when /api/stats can't be reached.

   Run after adding/removing content:
     npm run generate:site-stats
   Check only (exit 1 if stale):
     npm run generate:site-stats -- --check

   The server also warns at startup if this file
   no longer matches the data (backend/server.js).
========================================== */

const fs = require("fs");
const path = require("path");
const { computeContentStats } = require("../backend/lib/siteStats");

const OUTPUT_FILE = path.join(__dirname, "..", "data", "site-stats.js");

function render(stats) {
    return `/* ==========================================
   GENERATED by scripts/generate-site-stats.js —
   do not edit by hand. Real content counts from
   data/*.js, shown by js/site-stats.js even when
   the server (/api/stats) can't be reached.
   Regenerate: npm run generate:site-stats
========================================== */

const SITE_CONTENT_STATS = ${JSON.stringify(stats, null, 4)};

if (typeof window !== "undefined") window.SITE_CONTENT_STATS = SITE_CONTENT_STATS;
if (typeof module !== "undefined") module.exports = SITE_CONTENT_STATS;
`;
}

const expected = render(computeContentStats());
const current = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, "utf8").replace(/\r\n/g, "\n") : "";

if (process.argv.includes("--check")) {
    if (current === expected) { console.log("data/site-stats.js is up to date."); process.exit(0); }
    console.error("data/site-stats.js is stale — run: npm run generate:site-stats");
    process.exit(1);
}

fs.writeFileSync(OUTPUT_FILE, expected);
console.log("Wrote data/site-stats.js");
